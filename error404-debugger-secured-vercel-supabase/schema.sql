create table if not exists public.participants (
  id text primary key,
  name text not null,
  type text not null,
  members text default '',
  solved integer default 0,
  pts integer default 0,
  time integer default 0,
  violations integer default 0,
  help integer default 0,
  qi integer default 0,
  status text default 'lobby',
  log jsonb not null default '[]'::jsonb,
  ts bigint not null,
  participant_token_hash text
);

create table if not exists public.activities (
  id bigint generated by default as identity primary key,
  participant_id text not null references public.participants(id) on delete cascade,
  event_type text not null,
  question integer,
  timestamp bigint not null,
  details jsonb default '{}'::jsonb
);

create index if not exists idx_activities_participant on public.activities(participant_id);
create index if not exists idx_activities_timestamp on public.activities(timestamp);

create table if not exists public.game_control (
  id integer primary key check (id = 1),
  question_index integer not null default 0,
  phase text not null default 'lobby',
  action text not null default 'init',
  action_at bigint not null default 0,
  revision integer not null default 0,
  updated_at timestamptz not null default now()
);

-- Safe upgrades for an existing installation; existing participant rows are preserved.
alter table public.participants add column if not exists log jsonb not null default '[]'::jsonb;
alter table public.participants add column if not exists participant_token_hash text;

insert into public.game_control (id, question_index, phase, action, action_at, revision)
values (1, 0, 'lobby', 'init', 0, 0)
on conflict (id) do nothing;

-- Browser clients must not access these tables directly. The Vercel API uses
-- SUPABASE_SERVICE_ROLE_KEY on the server; service_role bypasses RLS.
alter table public.participants enable row level security;
alter table public.activities enable row level security;
alter table public.game_control enable row level security;

revoke all on table public.participants, public.activities, public.game_control from public, anon, authenticated;
grant all on table public.participants, public.activities, public.game_control to service_role;

do $$
declare seq_name text;
begin
  seq_name := pg_get_serial_sequence('public.activities', 'id');
  if seq_name is not null then
    execute format('grant usage, select on sequence %s to service_role', seq_name);
  end if;
end $$;

